// Batch 12 (v9): caret in front of a list item + Enter keeps the list; pasted lists become real lists (phone AND desktop).
const { chromium } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };
const srv = http.createServer((q, r) => { const f = path.join(root, q.url === '/' ? 'index.html' : q.url.split('?')[0]); fs.readFile(f, (e, d) => e ? (r.writeHead(404), r.end()) : (r.writeHead(200, { 'content-type': types[path.extname(f)] || 'text/plain' }), r.end(d))); });
const results = []; const ok = (n, c, x) => { results.push(!!c); console.log((c ? 'PASS ' : 'FAIL ') + n + (!c && x ? ' -> ' + x : '')); };
(async () => {
  await new Promise(r => srv.listen(0, r));
  const browser = await chromium.launch({ executablePath: process.env.CHROME });
  const url = 'http://localhost:' + srv.address().port + '/'; const errs = [];
  for (const [label, vp] of [['phone', { width: 390, height: 844 }], ['desktop', { width: 1280, height: 800 }]]) {
    const page = await (await browser.newContext({ viewport: vp })).newPage();
    page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()));
    await page.goto(url); await page.waitForSelector('#newNote');
    await page.click('#newNote'); await page.waitForSelector('#edBody'); await page.waitForTimeout(300);
    const html = () => page.evaluate(() => NotesEditor.getHTML().replace(/<br>/g, '').replace(/\s+/g, ' '));
    const setBody = h => page.evaluate(h => { const b = document.getElementById('edBody'); b.innerHTML = h; b.focus(); }, h);
    const caret = (sel, idx, off) => page.evaluate(([sel, idx, off]) => { const b = document.getElementById('edBody'); const el = b.querySelectorAll(sel)[idx]; const t = el.firstChild && el.firstChild.nodeType === 3 ? el.firstChild : el; const r = document.createRange(); if (t.nodeType === 3) r.setStart(t, off); else r.setStart(t, 0); r.collapse(true); const s = getSelection(); s.removeAllRanges(); s.addRange(r); b.focus(); }, [sel, idx, off || 0]);
    const paste = (text, htmlData) => page.evaluate(([text, htmlData]) => { const b = document.getElementById('edBody'); const dt = new DataTransfer(); if (text != null) dt.setData('text/plain', text); if (htmlData) dt.setData('text/html', htmlData); b.dispatchEvent(new ClipboardEvent('paste', { clipboardData: dt, bubbles: true, cancelable: true })); }, [text, htmlData]);
    const L = label + ': ';

    /* ---- item 3: caret before the list ---- */
    await setBody('<ol><li>one</li><li>two</li><li>three</li></ol>');
    await caret('li', 0, 0); await page.keyboard.press('Enter'); await page.keyboard.type('top');
    ok(L + 'Enter in front of the first number adds a line above, list stays 1-2-3', (await html()) === '<div>top</div><ol><li>one</li><li>two</li><li>three</li></ol>', await html());
    await setBody('<ul><li>a</li><li>b</li></ul>');
    await caret('li', 0, 0); await page.keyboard.press('Enter'); await page.keyboard.type('x');
    ok(L + 'same for a bulleted list', (await html()) === '<div>x</div><ul><li>a</li><li>b</li></ul>', await html());
    await setBody('<ul class="checklist"><li class="done">a</li><li>b</li></ul>');
    await caret('li', 0, 0); await page.keyboard.press('Enter'); await page.keyboard.type('x');
    ok(L + 'same for a checklist (done state kept)', (await html()) === '<div>x</div><ul class="checklist"><li class="done">a</li><li>b</li></ul>', await html());
    await setBody('<ol><li>one</li><li>two</li><li>three</li></ol>');
    await caret('li', 0, 0); await page.keyboard.press('ArrowUp'); await page.keyboard.type('title');
    ok(L + 'Arrow Up from the first item moves into a new line above', (await html()) === '<div>title</div><ol><li>one</li><li>two</li><li>three</li></ol>', await html());
    await setBody('<div>intro</div><ol><li>one</li><li>two</li></ol>');
    await caret('li', 0, 0); await page.keyboard.press('Enter');
    ok(L + 'with a line above already, Enter before "1." adds an empty item and keeps ONE list (1 empty, 2 one, 3 two)', (await html()) === '<div>intro</div><ol><li></li><li>one</li><li>two</li></ol>', await html());
    await setBody('<ol><li>one</li><li>two</li><li>three</li></ol>');
    await caret('li', 1, 0); await page.keyboard.press('Enter');
    ok(L + 'Enter in front of a middle item keeps one list (4 items, numbers 1-2-3-4)', (await html()) === '<ol><li>one</li><li></li><li>two</li><li>three</li></ol>', await html());
    await setBody('<ol><li>one</li><li>two</li></ol>');
    await caret('li', 0, 1); await page.keyboard.press('Enter'); await page.keyboard.type('X');
    ok(L + 'Enter in the middle of an item splits it, list intact', (await html()) === '<ol><li>o</li><li>Xne</li><li>two</li></ol>', await html());
    await setBody('<ol><li>one</li></ol>');
    await caret('li', 0, 3); await page.keyboard.press('Enter'); await page.keyboard.press('Enter'); await page.keyboard.type('after');
    ok(L + 'Enter on an empty item still leaves the list (typing below it)', (await html()) === '<ol><li>one</li></ol><div>after</div>', await html());
    await setBody('<ul class="checklist"><li>a</li></ul>');
    await caret('li', 0, 0);
    await page.evaluate(() => { const li = document.querySelector('#edBody li'); const r = li.getBoundingClientRect(); window.__p = [r.left + 60, r.top + 8]; });
    const pt = await page.evaluate(() => window.__p); await page.mouse.click(pt[0], pt[1]);
    ok(L + 'tapping the text of a checklist item does not tick it', !(await page.evaluate(() => document.querySelector('#edBody li').classList.contains('done'))));

    /* ---- item 4: pasted lists ---- */
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('- milk\n- eggs\n- bread');
    ok(L + 'pasted "- " lines become a bulleted list', (await html()) === '<ul><li>milk</li><li>eggs</li><li>bread</li></ul>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('1. first\n2. second\n3) third');
    ok(L + 'pasted "1." / "2." / "3)" lines become a numbered list', (await html()) === '<ol><li>first</li><li>second</li><li>third</li></ol>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('3. c\n4. d');
    ok(L + 'a pasted list starting at 3 keeps its numbers', (await html()) === '<ol start="3"><li>c</li><li>d</li></ol>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('☐ todo\n☑ done thing\n[ ] also\n[x] checked');
    ok(L + 'pasted checkbox lines become a checklist (☑/[x] done)', (await html()) === '<ul class="checklist"><li>todo</li><li class="done">done thing</li><li>also</li><li class="done">checked</li></ul>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('• one\n• two');
    ok(L + 'pasted • lines (our own copy format) become bullets', (await html()) === '<ul><li>one</li><li>two</li></ul>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('Shopping\n- milk\n- eggs\nthanks\n1. a\n2. b');
    ok(L + 'mixed text keeps normal lines and converts each list run', (await html()) === '<div>Shopping</div><ul><li>milk</li><li>eggs</li></ul><div>thanks</div><ol><li>a</li><li>b</li></ol>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('Roses are - red\n- just one dash line\nplain');
    ok(L + 'a single dash line inside prose is left alone', !/<ul>|<ol>/.test(await html()), await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('- only one');
    ok(L + 'one pasted item on an empty line becomes a list item', (await html()) === '<ul><li>only one</li></ul>', await html());
    await setBody('<div>text</div>'); await caret('div', 0, 4); await page.keyboard.type(' ');
    await paste('- only one');
    ok(L + 'but a single "- " pasted into a sentence stays text', !/<ul>/.test(await html()) && /text.- only one/.test((await html()).replace(/&nbsp;/g, ' ')), await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('plain paste\nwithout markers');
    ok(L + 'normal multi-line text is unchanged (no list)', !/<ul>|<ol>/.test(await html()) && /plain paste/.test(await html()) && /without markers/.test(await html()), await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('1. x\n2. y', '<p>1. x</p><p>2. y</p>');
    ok(L + 'html paste with "1."/"2." paragraphs becomes a numbered list', (await html()) === '<ol><li>x</li><li>y</li></ol>', await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('- a\n- b', '<div><b>- bold</b></div><div>- plain</div>');
    ok(L + 'html paste keeps bold inside the list item', /<ul><li><b>bold<\/b><\/li><li>plain<\/li><\/ul>/.test(await html()), await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('a\nb', '<ul><li>real</li><li>list</li></ul>');
    ok(L + 'real <ul> html still pastes as a list', /<ul><li>real<\/li><li>list<\/li><\/ul>/.test(await html()), await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('- a\n- b'); await page.keyboard.type('!'); await page.keyboard.press('Enter'); await page.keyboard.type('c');
    ok(L + 'you can keep typing in the pasted list (Enter adds items)', (await html()) === '<ul><li>a</li><li>b!</li><li>c</li></ul>', await html());
    // saves and reloads
    const saved = await page.evaluate(() => NotesEditor.getHTML());
    ok(L + 'the saved HTML keeps the lists', /<ul>/.test(saved));
    await setBody('<div>keep</div><div><br></div>'); await caret('div', 1, 0);
    await paste('- u1\n- u2');
    await page.evaluate(() => document.execCommand('undo'));
    ok(L + 'undo takes a pasted list back out', !/<ul>|<li>/.test(await html()) && /keep/.test(await html()), await html());
    await setBody('<div><br></div>'); await caret('div', 0, 0);
    await paste('7. a\n8. b');
    const rt = await page.evaluate(() => { const h = NotesEditor.getHTML(); NotesEditor.load(h); return NotesEditor.getHTML(); });
    ok(L + 'a list starting at 7 survives save / load', /<ol start="7">/.test(rt), rt);
  }
  ok('no console/page errors', errs.length === 0, errs.join(' | '));
  const pass = results.filter(Boolean).length; console.log(`\n${pass}/${results.length} passed`);
  await browser.close(); srv.close(); process.exit(pass === results.length ? 0 : 1);
})().catch(e => { console.error(e); process.exit(2); });
